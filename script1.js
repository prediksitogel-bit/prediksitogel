/* =========================================
   BUKA / TUTUP BUKU MIMPI
========================================= */

function toggleBukuMimpi() {

    const content =
        document.getElementById(
            "bukuMimpiContent"
        );

    const button =
        document.getElementById(
            "btnBukaMimpi"
        );

    if (!content || !button) return;


    const sedangTutup =
        content.style.display === "none" ||
        content.style.display === "";


    if (sedangTutup) {

        /* BUKA */

        content.style.display = "block";

        button.textContent = "TUTUP";

        button.classList.add(
            "aktif"
        );


        /* Render data 00-99 */

        if (
            typeof renderDreamBook ===
            "function"
        ) {

            renderDreamBook();

        }


    } else {

        /* TUTUP */

        content.style.display = "none";

        button.textContent = "BUKA";

        button.classList.remove(
            "aktif"
        );

    }

}

function fokusCariMimpi() {

    const content =
        document.getElementById("bukuMimpiContent");

    const button =
        document.getElementById("btnBukaMimpi");

    const search =
        document.getElementById("searchMimpi");


    // Jika masih tertutup → buka
    if (
        content &&
        content.style.display === "none"
    ) {

        toggleBukuMimpi();

    }


    // Fokus ke pencarian
    setTimeout(() => {

        if (search) {

            search.focus();

            search.scrollIntoView({
                behavior: "smooth",
                block: "center"
            });

        }

    }, 100);

}